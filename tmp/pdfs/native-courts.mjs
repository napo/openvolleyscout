function shortName(name) {
  const trimmed = name.trim();
  if (!trimmed || /^#\d+$/.test(trimmed)) return "";
  const parts = trimmed.split(/\s+/);
  const last = parts[parts.length - 1] ?? "";
  return last.length > 14 ? `${last.slice(0, 13)}\u2026` : last;
}
